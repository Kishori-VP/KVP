def clean_child_name(raw_name: str | None) -> str:
    """Clean common inconsistencies in child names."""
    if not raw_name:
        return ""
    name = str(raw_name).strip()
    # Remove role suffixes mistakenly appended to names
    name = re.sub(r"\s+प्रमुख\b", "", name)
    name = re.sub(r"\s+उपप्रमुख\b", "", name)
    # Fix accidental space typos in known surnames
    name = name.replace("आष्टउ रकर", "आष्टुरकर")
    # Normalize multiple whitespace characters
    name = re.sub(r"\s+", " ", name)
    return name.strip()


def infer_gender(name: str | None, default: str = "boy") -> str:
    """Infer gender ('girl' or 'boy') from a Marathi / Indian name."""
    cleaned = clean_child_name(name)
    if not cleaned:
        return default
    first_name = cleaned.split()[0]
    if first_name in GIRL_FIRST_NAMES:
        return "girl"
    if first_name in BOY_FIRST_NAMES:
        return "boy"
    return default
